/**
 * 领域层：i18n 国际化模块
 *
 * 轻量自研 key 字典方案：无外部依赖，纯 ES module。
 * - 语言自动检测：navigator.language 以 "zh" 开头判定为中文，其余为英文
 * - 不提供手动切换语言入口（按需求）
 * - t(key, params) 支持 {placeholder} 插值
 *
 * 字典为 { zh, en } 双层结构，key 按功能模块分组命名。
 * 后端 WS/REST 下发的用户可见消息均已改为错误码（code），
 * 前端统一经 i18nError(msg) 映射成本地文案。
 */

const SUPPORTED_LANGS = ['zh', 'en'];

/** 自动检测语言：navigator.language 以 "zh" 开头 → zh，否则 en */
function detectLanguage() {
  const lang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  return lang.startsWith('zh') ? 'zh' : 'en';
}

