/**
 * 取当前语言译文。
 * @param {string} key 字典 key
 * @param {object} [params] 插值参数 {placeholder: value}
 * @returns {string} 译文；缺失时回退英文，再缺失回退 key 本身
 */
export function t(key, params) {
  const table = dict[LANG] || dict.en;
  let text = table[key];
  if (text === undefined) {
    text = dict.en[key];
  }
  if (text === undefined) {
    text = key;
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split('{' + k + '}').join(String(v));
    }
  }
  return text;
}

/**
 * 后端错误消息 → 本地文案。
 * 后端下发的用户可见错误统一为 {code, params} 结构（无中文字面量跨网传输）；
 * 兼容历史 message 透传（如动态异常文本）。
 * @param {object} msg 后端消息（含 code / params / message 字段）
 * @returns {string} 本地化文案
 */
export function i18nError(msg) {
  if (msg && msg.code) {
    return t(msg.code, msg.params || {});
  }
  return (msg && msg.message) || '';
}

/**
 * 应用静态 HTML 初始文案。
 * 静态页面中的用户可见文本标记 data-i18n="key"（textContent）、
 * data-i18n-title="key"（title 属性）、data-i18n-placeholder="key"（placeholder 属性），
 * 页面加载完成后统一替换为当前语言译文。
 */
export function applyStaticText() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    if (key) el.title = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (key) el.placeholder = t(key);
  });
}